import { supabase } from '@/lib/supabase';
import type { PurchaseOrder } from '../types';
import {
  buildCofHtml,
  openCofHtmlInNewTab,
  type CofFieldOverrides,
} from './generateCofPdf';

type RequestorInfo = Parameters<typeof buildCofHtml>[1];

async function fetchRequestorInfo(poId: string): Promise<RequestorInfo> {
  try {
    const { data, error } = await supabase.rpc('get_po_requestor_info', { p_po_id: poId });
    if (error) {
      console.warn('[Warehouse COF] get_po_requestor_info error:', error);
      return { company: null, profile: null };
    }
    const obj = (data || {}) as Partial<RequestorInfo>;
    return {
      company: obj.company ?? null,
      profile: obj.profile ?? null,
    };
  } catch (e) {
    console.warn('[Warehouse COF] get_po_requestor_info exception:', e);
    return { company: null, profile: null };
  }
}

