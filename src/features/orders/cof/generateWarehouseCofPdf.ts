function attachWarehouseSignoff(html: string): string {
  const withCss = html.replace('</style>', `${WAREHOUSE_SIGNOFF_CSS}\n</style>`);
  return withCss.replace(
    '<div class="footer-note">Generated by B1G Ordering System</div>',
    `${WAREHOUSE_SIGNOFF_HTML}\n    <div class="footer-note">Generated by B1G Ordering System</div>`
  );
}

/**
 * Warehouse Customer Order Form — same COF layout as generateCofPdf,
 * plus the warehouse prepared/checked/verified/courier sign-off table.
 */
export async function generateAndOpenWarehouseCofPdf(
  po: PurchaseOrder,
  overrides?: CofFieldOverrides
) {
  const requestor = await fetchRequestorInfo(po.id);
  const html = attachWarehouseSignoff(buildCofHtml(po, requestor, overrides));
  openCofHtmlInNewTab(html);
}
